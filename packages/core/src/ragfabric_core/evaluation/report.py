"""Render one stored batch as Markdown (``docs/benchmarks/latest.md``, D19).

Everything printed comes from the stored rows. The header names the run (date,
commit, models, judge) and says plainly that it is one run on one setup, never
a general claim (ADR 0004). An unmeasured value prints as ``n/a``.
"""

from __future__ import annotations

from ragfabric_core.evaluation.dataset import QuestionType
from ragfabric_core.evaluation.runner import count_refusals
from ragfabric_core.models.evaluation import EvaluationResult, EvaluationRun

NA = "n/a"


def _external(run: EvaluationRun) -> dict | None:
    """Provenance of a run whose answers were written outside RagFabric, else ``None``."""
    meta = run.summary.get("meta") or {}
    if meta.get("answer_source") is None:
        return None
    return meta


CATEGORY_METRICS = (
    ("hit", "Hit rate"),
    ("reciprocal_rank", "MRR"),
    ("correctness", "Correctness"),
    ("citation_correct", "Citation correctness"),
)


def _num(value, digits: int = 2) -> str:
    if value is None:
        return NA
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    return f"{value:.{digits}f}"


def _cost(value) -> str:
    return NA if value is None else f"${value:.4f}"


def render_report(
    runs: list[tuple[EvaluationRun, list[EvaluationResult]]],
    *,
    agreement: dict | None = None,
) -> str:
    if not runs:
        raise ValueError("no runs in this batch")
    first = runs[0][0]
    meta = first.summary.get("meta", {})
    ran = [(run, rows) for run, rows in runs if run.summary.get("status") != "skipped"]
    skipped = [run for run, _ in runs if run.summary.get("status") == "skipped"]
    judge_kind = meta.get("judge_kind", "")
    judge_label = (
        "lexical word overlap (deterministic, not the LLM rubric)"
        if judge_kind == "lexical"
        else f"LLM rubric, model {meta.get('judge_model') or NA}, prompt {meta.get('judge_prompt_version')}"
    )
    out: list[str] = []
    out.append("# Latest evaluation run")
    out.append("")
    out.append(
        "> Generated by `ragfabric eval` from stored rows; do not edit by hand. **This is one run "
        "on one setup, not a benchmark.** Per ADR 0004 every number below is what happened on the "
        "named corpus, questions, models and machine on the date shown. Judge scores are an "
        "estimate; cost is an estimate from configured pricing."
    )
    out.append("")
    out.append("| Run | Value |")
    out.append("|---|---|")
    rows_meta = [
        ("Batch", first.name),
        ("Date (UTC)", first.started_at.strftime("%Y-%m-%d %H:%M") if first.started_at else NA),
        ("Commit", f"`{first.commit_sha}`" if first.commit_sha else NA),
        ("RagFabric version", meta.get("ragfabric_version", NA)),
        ("Question set", f"{first.question_set} (`{meta.get('questions_hash', NA)}`)"),
        ("Corpus", f"{meta.get('collection', NA)} (`{meta.get('corpus_hash', NA)}`)"),
        ("LLM", f"{meta.get('llm_provider', NA)} / {first.llm_model or NA}"),
        ("Embeddings", first.embedding_model or NA),
        ("Judge", judge_label),
        ("top_k", str(meta.get("top_k", NA))),
    ]
    out += [f"| {k} | {v} |" for k, v in rows_meta]
    out.append("")
    outside = [(run, _external(run)) for run, _ in ran if _external(run)]
    if outside:
        out.append("## Answers from outside RagFabric")
        out.append("")
        out.append(
            "> **The runs below were not answered by a RagFabric API call.** Someone else's model "
            "wrote the answers from the exported passages, and RagFabric only scored them. They "
            "are not a controlled run: read them with the label and date shown, never as a "
            "model tested through its API. The retrieved passages and the scoring code are the "
            "same as for the other runs."
        )
        out.append("")
        out.append(
            "| Target | Answered by | Answer source | Prompt file (SHA-256) | Export date | "
            "Reported model |"
        )
        out.append("|---|---|---|---|---|---|")
        for run, ext in outside:
            reported = ", ".join(ext.get("reported_models") or []) or NA
            digest = (ext.get("prompt_file_sha256") or "")[:12]
            out.append(
                f"| {run.strategy} | {ext.get('answered_by') or NA} | "
                f"{ext.get('answer_source')} | {f'`{digest}`' if digest else NA} | "
                f"{ext.get('export_date') or NA} | {reported} |"
            )
        out.append("")
        problems = [
            (run, (run.summary.get("meta") or {}).get("import_errors", {}).get("counts") or {})
            for run, _ in outside
        ]
        for run, counts in problems:
            shown = {k: v for k, v in counts.items() if v}
            if shown:
                text = ", ".join(f"{k} {v}" for k, v in shown.items())
                out.append(f"- `{run.strategy}` import errors, none scored as zero: {text}.")
        if any(c for _, c in problems if any(c.values())):
            out.append("")
    out.append("## Overall")
    out.append("")
    out.append(
        "| Target | Questions | Errors | Refusals | Hit rate | MRR | Precision | Recall | Correctness | "
        "Faithfulness | Context relevance | Citation correctness | p50 ms | p95 ms | LLM calls | "
        "Tokens in / out | Est. cost |"
    )
    out.append("|" + "---|" * 17)
    for run, rows in ran:
        s = run.summary
        m = s.get("metrics", {})
        lat = s.get("latency_ms", {})
        out.append(
            f"| {run.strategy}{' (external answers)' if _external(run) else ''} | {s.get('questions', 0)} | {s.get('errors', 0)} | "
            f"{count_refusals(rows)} | "
            f"{_num(m.get('hit'))} | {_num(m.get('reciprocal_rank'))} | "
            f"{_num(m.get('precision'))} | {_num(m.get('recall'))} | "
            f"{_num(m.get('correctness'))} | {_num(m.get('faithfulness'))} | "
            f"{_num(m.get('context_relevance'))} | {_num(m.get('citation_correct'))} | "
            f"{_num(lat.get('p50'))} | {_num(lat.get('p95'))} | {_num(s.get('llm_calls'))} | "
            f"{_num(s.get('input_tokens'))} / {_num(s.get('output_tokens'))} | "
            f"{_cost(s.get('estimated_cost_usd'))} |"
        )
    out.append("")
    for field, title in CATEGORY_METRICS:
        out.append(f"## {title} by category")
        out.append("")
        out.append("| Category | " + " | ".join(run.strategy for run, _ in ran) + " |")
        out.append("|---|" + "---|" * len(ran))
        for category in QuestionType:
            cells = [
                _num(run.summary.get("by_category", {}).get(str(category), {}).get(field))
                for run, _ in ran
            ]
            out.append(f"| {category} | " + " | ".join(cells) + " |")
        out.append("")
    if agreement:
        out.append("## Router")
        out.append("")
        out.append(
            f"`auto` matched the best fixed strategy's correctness on {agreement['matched']} of "
            f"{agreement['measured']} measured questions."
        )
        out.append("")
        out.append("| Question | auto chose | auto | Best fixed | Best strategies | Matched |")
        out.append("|---|---|---|---|---|---|")
        chosen = {}
        for run, rows in ran:
            if run.strategy == "auto":
                chosen = {r.question_id: r.details.get("strategy_used") for r in rows}
        for q in agreement["questions"]:
            out.append(
                f"| {q['question_id']} | {chosen.get(q['question_id']) or NA} | "
                f"{_num(q['auto'])} | {_num(q['best'])} | {', '.join(q['best_strategies'])} | "
                f"{'yes' if q['matched'] else 'no'} |"
            )
        out.append("")
    if skipped:
        out.append("## Skipped targets")
        out.append("")
        out += [f"- `{run.strategy}`: {run.summary.get('skipped')}" for run in skipped]
        out.append("")
    out.append("## How to read this")
    out.append("")
    out.append(
        "Refusals are answers that said the documents do not contain the answer; read them "
        "next to the hit rate, since a refusal with a hit is a generation failure, not a "
        "retrieval one. "
        "Metric definitions are in [docs/evaluation.md](../evaluation.md). Retrieval metrics are "
        "computed from the expected sources; generation metrics come from the judge named above; "
        "citation correctness is deterministic. A small question set means one question moves a "
        "category mean by a third; read the shape, not the decimals."
    )
    out.append("")
    return "\n".join(out)
